"""Downloadable PDF analysis report and DOCX export for built resumes."""
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INK = colors.HexColor("#0f1c2e")
BLUE = colors.HexColor("#2457f5")


def build_pdf(a):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title="Resume analysis report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=INK, fontSize=20, alignment=0, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=BLUE, fontSize=13, spaceBefore=12, spaceAfter=4)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10, leading=14)
    P = lambda t, s=body: Paragraph(escape(str(t)), s)
    d = a.data
    story = [P("Resume Analysis Report", h1),
             P(f"File: {a.resume.original_name}   |   Date: {a.created_at:%d %b %Y}"
               + (f"   |   Target role: {a.job_title}" if a.job_title else ""))]

    rows = [["Overall score", f"{a.overall_score}/100  ({a.label})"], ["Skills", f"{a.skills_score}/100"],
            ["Education", f"{a.education_score}/100"], ["Formatting", f"{a.format_score}/100"],
            ["Keywords & impact", f"{a.keyword_score}/100"]]
    if a.match_score is not None:
        rows.append(["Job match", f"{a.match_score}%"])
    t = Table(rows, colWidths=[60 * mm, 60 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c9d1dd")),
                           ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2f9")),
                           ("FONTSIZE", (0, 0), (-1, -1), 10), ("PADDING", (0, 0), (-1, -1), 6)]))
    story += [Spacer(1, 8), t]

    parsed = d.get("parsed", {})
    story += [P("Skills detected", h2), P("Technical: " + (", ".join(parsed.get("tech_skills", [])) or "none detected")),
              P("Soft: " + (", ".join(parsed.get("soft_skills", [])) or "none detected"))]
    if parsed.get("education"):
        story += [P("Education", h2)] + [P("- " + e) for e in parsed["education"]]
    if parsed.get("projects"):
        story += [P("Projects", h2)] + [P("- " + e) for e in parsed["projects"]]

    m = d.get("match")
    if m:
        story += [P("Job description match", h2), P(f"Matched skills: {', '.join(m['matched']) or 'none'}"),
                  P(f"Missing skills: {', '.join(m['missing_skills']) or 'none'}"),
                  P(f"Missing keywords: {', '.join(m['missing_keywords']) or 'none'}")]

    story.append(P("Improvement suggestions", h2))
    for s in d.get("suggestions", []):
        story.append(P(f"[{s['priority'].upper()}] {s['title']}: {s['detail']}"))
        story.append(Spacer(1, 3))

    ai_pack = d.get("ai") or {}
    if ai_pack:
        story += [P("AI review (Gemini)", h2), P(ai_pack.get("summary") or "")]
        for r in ai_pack.get("rewrites") or []:
            story.append(P(f"Rewrite: {r.get('before','')} → {r.get('after','')}"))
        if ai_pack.get("ats_keywords"):
            story.append(P("ATS keywords to add: " + ", ".join(ai_pack["ats_keywords"])))
        if ai_pack.get("interview"):
            story.append(P("Interview prep", h2))
            for q in ai_pack["interview"]:
                story.append(P(f"Q: {q.get('q','')} — {q.get('tip','')}"))

    if d.get("jobs"):
        story.append(P("Recommended job roles", h2))
        for j in d["jobs"]:
            story.append(P(f"- {j['role']} ({j['pct']}% skill fit)" + (f"; to learn: {', '.join(j['missing'])}" if j["missing"] else "")))
    story += [Spacer(1, 14), P("Generated by ResumeIQ. This report is private to your account.")]
    doc.build(story)
    return buf.getvalue()


def build_docx(r):
    import docx
    from docx.shared import Pt
    d = docx.Document()
    d.styles["Normal"].font.name = "Calibri"
    d.styles["Normal"].font.size = Pt(10.5)
    d.add_heading(r.full_name, 0)
    if r.headline:
        d.add_paragraph(r.headline)
    if r.contact_list:
        d.add_paragraph("  |  ".join(r.contact_list))
    if r.summary:
        d.add_heading("Summary", 2)
        d.add_paragraph(r.summary)
    if r.skill_list:
        d.add_heading("Skills", 2)
        d.add_paragraph(", ".join(r.skill_list))
    for title, blocks in (("Experience", r.experience_blocks), ("Education", r.education_blocks), ("Projects", r.project_blocks)):
        if blocks:
            d.add_heading(title, 2)
            for b in blocks:
                p = d.add_paragraph()
                p.add_run(b["parts"][0]).bold = True
                if len(b["parts"]) > 1:
                    p.add_run("  |  " + "  |  ".join(b["parts"][1:]))
                for bl in b["bullets"]:
                    d.add_paragraph(bl, style="List Bullet")
    if r.cert_list:
        d.add_heading("Certifications", 2)
        for c in r.cert_list:
            d.add_paragraph(c, style="List Bullet")
    out = io.BytesIO()
    d.save(out)
    return out.getvalue()
